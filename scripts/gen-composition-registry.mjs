#!/usr/bin/env node
/**
 * Generate the registry of declared animations.
 *
 * The sibling of gen-patch-registry.mjs. Adding an animation used to mean three
 * edits in `compositions-info.tsx` — an import, a member in a union type, and an
 * entry in the object — which is exactly the kind of hand-maintained list that
 * drifts from what is actually on disk. This derives it from
 * `compositions/*[/]composition.json` instead.
 *
 * The imports are written out statically rather than resolved at runtime: a
 * bundler cannot follow `import(variable)`, and the sketches have to end up in
 * the build.
 *
 * Usage:
 *   node scripts/gen-composition-registry.mjs           # write the file
 *   node scripts/gen-composition-registry.mjs --check   # fail if it would change
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { readCompositions } from "./composition-manifest.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(
  ROOT,
  "components/compositions/compositions-declared.generated.ts",
);

/**
 * O vocabulário de dados, transposto de JSON para TypeScript.
 *
 * O JSON continua sendo a fonte — é o que `composition-manifest.mjs` lê para
 * validar. Mas o runtime não pode importá-lo: `node --test` exige
 * `with { type: "json" }` e o bundler não, então o mesmo import não serve aos
 * dois. Transpor resolve sem escolher um lado, e o `--check` garante que a
 * cópia nunca discorde do original.
 */
const VOCABULARY_SOURCE = path.join(ROOT, "lib/gaia-composition-attributes.json");
const VOCABULARY_OUTPUT = path.join(
  ROOT,
  "lib/gaia-composition-attributes.generated.ts",
);

function renderVocabulary() {
  const bruto = JSON.parse(fs.readFileSync(VOCABULARY_SOURCE, "utf8"));
  const { $comment, ...aliases } = bruto.aliases;

  return [
    "/**",
    " * AUTOGENERATED by scripts/gen-composition-registry.mjs — do not edit by hand.",
    " *",
    " * Source of truth: lib/gaia-composition-attributes.json",
    " */",
    "",
    "export const COMPOSITION_ATTRIBUTES =",
    `  ${JSON.stringify(bruto.attributes, null, 2).replace(/\n/g, "\n  ")} as const;`,
    "",
    "export const COMPOSITION_ATTRIBUTE_ALIASES =",
    `  ${JSON.stringify(aliases, null, 2).replace(/\n/g, "\n  ")} as const;`,
    "",
  ].join("\n");
}

/** camelCase → PascalCase, para o nome do import. */
function pascal(id) {
  return id.charAt(0).toUpperCase() + id.slice(1);
}

function literal(valor) {
  return JSON.stringify(valor);
}

function sketchFile(slug) {
  for (const nome of ["sketch.tsx", "sketch.js"]) {
    if (fs.existsSync(path.join(ROOT, "compositions", slug, nome))) {
      // O import não leva extensão: o resolvedor do Next escolhe.
      return `@/compositions/${slug}/sketch`;
    }
  }
  return null;
}

function render(compositions) {
  const linhas = [];

  linhas.push("/**");
  linhas.push(" * AUTOGENERATED by scripts/gen-composition-registry.mjs — do not edit by hand.");
  linhas.push(" *");
  linhas.push(" * Source of truth: compositions/<slug>/composition.json plus the sketch");
  linhas.push(" * beside it. Run `npm run compositions:codegen` after changing either.");
  linhas.push(" */");
  linhas.push("");
  linhas.push('import { createComposition } from "./composition-runtime";');
  linhas.push('import type { CompositionManifest } from "./composition-runtime";');
  linhas.push("");

  for (const { slug, manifest } of compositions) {
    linhas.push(`import ${pascal(manifest.id)}Sketch from "${sketchFile(slug)}";`);
  }

  linhas.push("");
  linhas.push("export const DECLARED_COMPOSITION_MANIFESTS = {");

  for (const { manifest } of compositions) {
    linhas.push(`  ${manifest.id}: {`);
    linhas.push(`    id: ${literal(manifest.id)},`);
    linhas.push(`    label: ${literal(manifest.label)},`);
    linhas.push(`    attributes: ${literal(manifest.attributes)},`);
    linhas.push(`    audio: ${literal(manifest.audio)},`);
    linhas.push(`    thumb: ${literal(manifest.thumb)},`);
    if (manifest.author) linhas.push(`    author: ${literal(manifest.author)},`);
    if (manifest.openProcessingLink) {
      linhas.push(`    openProcessingLink: ${literal(manifest.openProcessingLink)},`);
    }
    if (manifest.keepMapPatch) linhas.push(`    keepMapPatch: true,`);
    linhas.push("  },");
  }

  linhas.push("} as const satisfies Record<string, CompositionManifest>;");
  linhas.push("");
  linhas.push("export const DECLARED_COMPOSITIONS = {");

  for (const { manifest } of compositions) {
    linhas.push(
      `  ${manifest.id}: createComposition(` +
        `DECLARED_COMPOSITION_MANIFESTS.${manifest.id}, ${pascal(manifest.id)}Sketch),`,
    );
  }

  linhas.push("};");
  linhas.push("");
  linhas.push("export type DeclaredCompositionName = keyof typeof DECLARED_COMPOSITIONS;");
  linhas.push("");

  return linhas.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const compositions = readCompositions().filter(({ manifest }) => manifest);

  for (const { slug, manifest } of compositions) {
    if (!sketchFile(slug)) {
      console.error(
        `erro: compositions/${slug} tem manifesto mas nenhum sketch. ` +
          `Rode npm run compositions:validate para o diagnóstico completo.`,
      );
      process.exit(1);
    }
    if (!manifest.id) {
      console.error(`erro: compositions/${slug}: falta o campo "id".`);
      process.exit(1);
    }
  }

  const saidas = [
    { arquivo: OUTPUT, conteudo: render(compositions) },
    { arquivo: VOCABULARY_OUTPUT, conteudo: renderVocabulary() },
  ];

  if (check) {
    for (const { arquivo, conteudo } of saidas) {
      const atual = fs.existsSync(arquivo) ? fs.readFileSync(arquivo, "utf8") : "";
      if (atual !== conteudo) {
        console.error(
          `${path.relative(ROOT, arquivo)} desatualizado. ` +
            "Rode `npm run compositions:codegen`.",
        );
        process.exit(1);
      }
    }
    console.log("Registro de animações está em dia.");
    return;
  }

  for (const { arquivo, conteudo } of saidas) fs.writeFileSync(arquivo, conteudo);
  console.log(
    `${path.relative(ROOT, OUTPUT)} — ${compositions.length} animação(ões) declarada(s)`,
  );
}

main();
