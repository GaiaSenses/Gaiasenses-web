#!/usr/bin/env node
/**
 * Generate the patch registry the app imports.
 *
 * This is the file that used to be maintained by hand in two places — the
 * `MAP3_PD4WEB_PATCHES` array and the `patchId` scattered through
 * `compositions-info.tsx`. Both are now derived from `patches/*[/]patch.json`
 * plus a scan of the `.pd` files, so publishing a patch touches no TypeScript.
 *
 * Usage:
 *   node scripts/gen-patch-registry.mjs           # write the file
 *   node scripts/gen-patch-registry.mjs --check   # fail if it would change
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadPatches, compositionEvents } from "./patch-manifest.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "app/[locale]/map3/pd4web-patches.generated.ts");

const DEFAULT_TUNING = { pollMs: 100, epsilon: 0.0001, accEpsilon: 0.05 };

/** Read the runtime hash the build step recorded next to the bundle, if any. */
function readRuntimeHash(slug) {
  const infoPath = path.join(ROOT, "public/patches", slug, "build-info.json");
  if (!fs.existsSync(infoPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(infoPath, "utf8")).runtime ?? null;
  } catch {
    return null;
  }
}

function literal(value) {
  return JSON.stringify(value);
}

function renderRecord(record, indent) {
  const keys = Object.keys(record).sort();
  if (keys.length === 0) return "{}";
  const pad = " ".repeat(indent);
  const inner = keys
    .map((key) => `${pad}  ${literal(key)}: ${literal(record[key])},`)
    .join("\n");
  return `{\n${inner}\n${pad}}`;
}

function renderPatch(patch) {
  const { manifest, receivers, senders, slug } = patch;
  const tuning = { ...DEFAULT_TUNING, ...(manifest.tuning ?? {}) };
  const runtime = readRuntimeHash(slug);

  const lines = [
    "  {",
    `    id: ${literal(manifest.id)},`,
    `    label: ${literal(manifest.label)},`,
    `    bundleFolder: ${literal(`patches/${slug}`)},`,
  ];

  if (runtime) lines.push(`    runtime: ${literal(runtime)},`);

  lines.push(
    "    activation: {",
    `      moments: ${literal(manifest.activation.moments)},`,
  );
  if (manifest.activation.compositions?.length) {
    lines.push(
      `      compositions: ${literal(manifest.activation.compositions)},`,
    );
  }
  lines.push("    },");

  lines.push(
    "    channels: {",
    `      receivers: ${renderRecord(receivers, 6)},`,
    `      senders: ${renderRecord(senders, 6)},`,
    "    },",
    `    tuning: { pollMs: ${tuning.pollMs}, epsilon: ${tuning.epsilon}, accEpsilon: ${tuning.accEpsilon} },`,
    "  },",
  );

  return lines.join("\n");
}

function renderCompositionPatchIds(patches) {
  const map = {};
  for (const patch of patches) {
    for (const composition of patch.manifest.activation.compositions ?? []) {
      map[composition] = patch.manifest.id;
    }
  }
  const keys = Object.keys(map).sort();
  if (keys.length === 0) return "{}";
  return `{\n${keys.map((key) => `  ${key}: ${literal(map[key])},`).join("\n")}\n}`;
}

function renderCompositionEvents() {
  const entries = Object.entries(compositionEvents.compositions).sort(
    ([a], [b]) => a.localeCompare(b),
  );

  const blocks = entries.map(([composition, contract]) => {
    const emits = (contract.emits ?? []).map((event) => event.name);
    const listensTo = (contract.listensTo ?? []).map((event) => event.name);
    return [
      `  ${composition}: {`,
      `    emits: ${literal(emits)},`,
      `    listensTo: ${literal(listensTo)},`,
      "  },",
    ].join("\n");
  });

  return `{\n${blocks.join("\n")}\n}`;
}

function render(patches) {
  return `/* eslint-disable */
/**
 * AUTOGENERATED by scripts/gen-patch-registry.mjs — do not edit by hand.
 *
 * Source of truth: patches/<slug>/patch.json plus the receivers found inside the
 * patch's own .pd files. Run \`npm run patches:codegen\` after changing either.
 */
import type { AvailableCompositionNames } from "@/components/compositions/compositions-info";
import type { Map3Pd4WebPatch } from "./pd4web-patches";

export const GENERATED_MAP3_PD4WEB_PATCHES = [
${patches.map(renderPatch).join("\n")}
] as const satisfies readonly Map3Pd4WebPatch[];

/**
 * Which patch plays with which p5 animation.
 *
 * The \`satisfies\` clause is the guard rail: a composition name that does not
 * exist becomes a tsc error, so a typo in a manifest cannot reach production.
 */
export const COMPOSITION_PATCH_ID = ${renderCompositionPatchIds(patches)} as const satisfies Partial<
  Record<AvailableCompositionNames, string>
>;

/**
 * The published event contract of each animation. These names belong to the
 * animation, not to any single patch — a new patch for lightningBolts works by
 * listening to [r bolt], with no code change here.
 */
export const COMPOSITION_EVENTS = ${renderCompositionEvents()} as const;
`;
}

function main() {
  const check = process.argv.includes("--check");
  const { patches, errors } = loadPatches();

  if (errors.length) {
    for (const error of errors) console.error(`erro: ${error}`);
    process.exit(1);
  }

  const next = render(patches);
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";

  if (check) {
    if (next !== current) {
      console.error(
        "O registro gerado está desatualizado.\n" +
          "Rode `npm run patches:codegen` e faça commit do resultado.",
      );
      process.exit(1);
    }
    console.log("Registro gerado está em dia.");
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, next);
  console.log(
    `${path.relative(ROOT, OUTPUT)} — ${patches.length} patch(es)` +
      (next === current ? " (sem mudanças)" : " (atualizado)"),
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
